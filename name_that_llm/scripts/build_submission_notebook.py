def build_notebook(config_path: str | Path) -> dict[str, Any]:
    """Render an nbformat v4 notebook from the canonical YAML configuration."""
    source, _, config, content = _load_config(config_path)
    candidate = config["inference"]["model_candidate"]
    model_type = config["training"]["models"][candidate].get("type")
    stylometry_source = _stylometry_source() if model_type == "style_char_tfidf" else ""
    code = _code_cell(config, hashlib.sha256(content).hexdigest(), stylometry_source)
    markdown = (
        "# Name That LLM — offline submission\n\n"
        "Generated from `configs/baseline.yaml`. This notebook uses only Kaggle's "
        "mounted Competition Data, installs/downloads nothing, and writes "
        "`submission.parquet` to the working directory.\n\n"
        f"Config version: **{config['version']}**; source: `{source.name}`.\n"
    )
    return {
        "cells": [
            {
                "cell_type": "markdown",
                "metadata": {},
                "source": markdown.splitlines(keepends=True),
            },
            {
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": code.splitlines(keepends=True),
            },
        ],
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def generate_notebook(config_path: str | Path, output_path: str | Path | None = None) -> Path:
    """Write the generated Notebook to disk and return its output path."""
    source, project_root, _, _ = _load_config(config_path)
    destination = Path(output_path) if output_path is not None else project_root / "notebooks" / "submission.ipynb"
    if not destination.is_absolute():
        destination = project_root / destination
    notebook = build_notebook(source)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        json.dumps(notebook, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    return destination


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/baseline.yaml")
    parser.add_argument("--output")
    args = parser.parse_args(argv)
    output = generate_notebook(args.config, args.output)
    print(f"generated Kaggle Notebook: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
